"""Offline diagnostics for a SmartStock installation.

It never calls a broker or online provider, never places orders, and does not
interpret 100% test pass as real-world predictive accuracy.
"""
from __future__ import annotations
from pathlib import Path
from datetime import datetime, timezone
import json
from preflight import check

ROOT=Path(__file__).resolve().parent
VERSION='10.12.0'

def inspect(root:Path=ROOT, now:datetime|None=None)->dict:
    root=Path(root)
    now=now or datetime.now(timezone.utc)
    structure=check(root)
    location=root/'reports'/'system_health_latest.json'
    previous={}
    errors=[]
    if location.exists():
        try:
            previous=json.loads(location.read_text(encoding='utf-8'))
            if not isinstance(previous,dict):raise ValueError('JSON object required')
        except (ValueError,OSError) as exc:
            errors.append(f'health report read failed: {type(exc).__name__} {exc}')
    else:errors.append('health report not yet generated by daily workflow')
    age_hours=None
    if previous.get('timestamp_utc'):
        try:
            ts=datetime.fromisoformat(previous['timestamp_utc'].replace('Z','+00:00'))
            if ts.tzinfo is None:raise ValueError('timestamp missing timezone')
            age_hours=round((now-ts).total_seconds()/3600,2)
        except (ValueError,TypeError) as exc:errors.append(f'health timestamp invalid: {exc}')
    status='failed' if structure['status']=='failed' else ('not_verified' if not previous else 'ok')
    if previous and (previous.get('status')!='ok' or previous.get('failure_count',0)>0):status='partial'
    if age_hours is not None and (age_hours<0 or age_hours>48):
        errors.append('health report timestamp is future or older than 48 hours')
        status='partial' if status!='failed' else status
    if previous and previous.get('version')!=VERSION:
        errors.append('last daily run version does not match installed version; rerun daily first')
        status='partial' if status!='failed' else status
    return {'check_version':VERSION,'timestamp_utc':now.isoformat(),
            'installation_status':structure['status'],'last_run_status':previous.get('status','unknown'),
            'last_run_version':previous.get('version'),
            'health_age_hours':age_hours,'status':status,'errors':errors,
            'local_missing':structure['missing'],'syntax_errors':structure['syntax_errors'],
            'note':'정적/저장 기록 진단이며 실시간 데이터·예측 실력 인증이 아닙니다.'}

def main():
    result=inspect()
    # Preserve an independent diagnosis even when the research process fails.
    target=ROOT/'reports'/'deployment_health_latest.json'
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('SMARTSTOCK_SYSTEM_CHECK '+json.dumps(result,ensure_ascii=False))
    # A missing/stale report is not a packaging failure; daily should be rerun.
    return 2 if result['installation_status']=='failed' else 0

if __name__=='__main__':raise SystemExit(main())
